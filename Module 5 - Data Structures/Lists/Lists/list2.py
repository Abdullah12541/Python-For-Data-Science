#Positve Indexing:

subjects = ["English", "Math", "Science", "Computer Science"]
print(subjects[0])
print(subjects[2])
print(subjects[3])

fruits = ["Apple", "Banana", "Orange", "Mango", "Grapes"]
print(fruits[1])
print(fruits[4])
print(fruits[0])

predictions = ["Cat", "Dog", "Birds", "Horse"]
print(predictions[1])
print(predictions[3])

#Negative Indexing:

subjects = ["English", "Math", "Science", "Computer Science"]
print(subjects[-1])
print(subjects[-4])
print(subjects[-2])

fruits = ["Apple", "Banana", "Orange", "Mango", "Grapes"]
print(fruits[-4])
print(fruits[-2])
print(fruits[-3])

predictions = ["Cat", "Dog", "Birds", "Horse"]
print(predictions[-1])
print(predictions[-3])

#Slicing:

subjects = ["English", "Math", "Science", "Computer Science"]
print(subjects[1:3])
print(subjects[0:2])


fruits = ["Apple", "Banana", "Orange", "Mango", "Grapes"]
print(fruits[0:5])


predictions = ["Cat", "Dog", "Birds", "Horse"]
print(predictions[0:3])

subjects = ["English", "Math", "Science", "Computer Science"]
print(subjects[:4])

subjects = ["English", "Math", "Science", "Computer Science"]
print(subjects[0:])

subjects = ["English", "Math", "Science", "Computer Science"]
print(subjects[:])

numbers = [10,20,30,40,50,60,70,80]
print(numbers[0:8:2])

numbers = [10,20,30,40,50,60,70,80]
print(numbers[8::-1])

numbers = [10,20,30,40,50,60,70,80]
print(numbers[8:2:-1])

numbers = [10,20,30,40,50,60,70,80]
print(numbers[3::-1])





